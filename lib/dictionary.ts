const DICTIONARIES: Record<string, DictionaryEntry[]> = {
  fi: FINNISH_DICTIONARY,
  sr: [...SERBIAN_DICTIONARY, ...SERBIAN_CYRILLIC_DICTIONARY],
  ka: GEORGIAN_DICTIONARY,
};

export function findWordsInText(
  text: string,
  language: string = "fi"
): DictionaryEntry[] {
  const dict = DICTIONARIES[language] ?? FINNISH_DICTIONARY;

  if (language === "ka") {
    const words = extractGeorgianWords(text);
    return dict.filter((entry) => words.includes(entry.word));
  }

  if (language === "sr") {
    const latinWords = extractLatinWords(text);
    const cyrillicWords = extractCyrillicWords(text);
    const allWords = [...new Set([...latinWords, ...cyrillicWords])];
    return dict.filter((entry) => allWords.includes(entry.word));
  }

  const words = text.toLowerCase().match(/[a-zäöåÄÖÅ]+/g) ?? [];
  const uniqueWords = [...new Set(words)];
  return dict.filter((entry) => uniqueWords.includes(entry.word.toLowerCase()));
}

function extractGeorgianWords(text: string): string[] {
  const georgianChars = text.match(/[\u10A0-\u10FF\u2D00-\u2D2F]+/g) ?? [];
  return [...new Set(georgianChars)];
}

function extractLatinWords(text: string): string[] {
  const words = text.toLowerCase().match(/[a-zčćžšđČĆŽŠĐ]+/g) ?? [];
  return [...new Set(words)];
}

function extractCyrillicWords(text: string): string[] {
  const words = text.match(/[а-яђјћџА-ЯЂЈЋЏ]+/g) ?? [];
  return [...new Set(words)];
}
